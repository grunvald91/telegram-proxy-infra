#!/usr/bin/env python3
"""One short-lived live website guest VPN trial, then compulsory revoke.
Never logs cookies, subscription tokens, credentials or client IPs.
Only inserts/revokes the unique entitlement generated by this probe.
"""
import base64
import hashlib
import http.cookies
import json
import subprocess
import time
import urllib.error
import urllib.request
import uuid

BASE="http://127.0.0.1:8792"
NAME="__Host-mnebyvpn_guest"
ID=None
H=None

def request(path,body=None,cookie=None):
    headers={'User-Agent':'mnebyvpn-live-trial-healthcheck/1'}
    method='GET' if body is None else 'POST'
    if body is not None:
        headers['Origin']='https://mnebyvpn.site'
        headers['Content-Type']='application/json'
    if cookie:
        headers['Cookie']=NAME+'='+cookie
    data=None if body is None else json.dumps(body).encode('utf8')
    req=urllib.request.Request(BASE+path,data,headers,method=method)
    with urllib.request.urlopen(req,timeout=12) as r:
        payload=json.loads(r.read(4096).decode())
        return payload,r.headers

def sql(query):
    cmd=['docker','exec','mnebyvpn-stage-postgres',
         'psql','-At','-v','ON_ERROR_STOP=1',
         '-U','mnebyvpn_stage','-d','mnebyvpn_stage','-c',query]
    p=subprocess.run(cmd,capture_output=True,text=True,timeout=12)
    if p.returncode:
        raise RuntimeError('SQL returned nonzero status')
    return p.stdout.strip()

def entitlement_for_hash(h):
    row=sql(
        "SELECT e.id FROM web_guest_claims g "+
        "JOIN trial_grants t ON t.guest_claim_hash=g.token_sha256 "+
        "JOIN entitlements e ON e.source_order_id=t.order_id "+
        "WHERE g.token_sha256='"+h+"' AND e.product='vpn'")
    if not row:return None
    return str(uuid.UUID(row))

def revoke(entitlement):
    entitlement=str(uuid.UUID(entitlement))
    sql("BEGIN; "+
        "UPDATE entitlements SET state='CANCELLED',revision=revision+1 "+
        "WHERE id='"+entitlement+"' AND state NOT IN ('CANCELLED','EXPIRED'); "+
        "INSERT INTO reconcile_outbox(entitlement_id,desired_revision) "+
        "SELECT id,revision FROM entitlements WHERE id='"+entitlement+"' "+
        "ON CONFLICT(entitlement_id,desired_revision) DO UPDATE "+
        "SET handled_at=NULL,next_attempt_at=clock_timestamp(); COMMIT;")
    # The DB has already revoked access; wait for node-level deprovisioning.
    for _ in range(20):
        row=sql(
            "SELECT CASE WHEN p.applied_revision=e.revision "+
            "AND e.state='CANCELLED' THEN 'yes' ELSE 'no' END "+
            "FROM entitlements e LEFT JOIN provisioning_state p "+
            "ON p.entitlement_id=e.id AND p.adapter='vpn' "+
            "WHERE e.id='"+entitlement+"'")
        if row=='yes':
            print('controlled_trial_xray_revoke_ack=verified',flush=True)
            return
        time.sleep(4)
    raise RuntimeError('Node revocation acknowledgement not observed within timeout')

def main():
    global ID,H
    offered,_=request('/api/plans')
    if offered.get('guestTrialEnabled') is not True:
        raise RuntimeError('Guest trial not advertised')
    print('website_guest_offer=true',flush=True)
    result,headers=request('/api/guest/trial',{'product':'vpn'})
    raw=headers.get('Set-Cookie')
    if not raw:
        raise RuntimeError('Guest session cookie not issued')
    parsed=http.cookies.SimpleCookie()
    parsed.load(raw)
    cookie=parsed[NAME].value
    if len(cookie)!=43:
        raise RuntimeError('Invalid browser session token')
    H=hashlib.sha256(cookie.encode()).hexdigest()
    if result.get('status')!='GRANTED':
        raise RuntimeError('Fresh trial was not granted')
    ID=entitlement_for_hash(H)
    if not ID:
        raise RuntimeError('Guest entitlement not created')
    print('guest_trial_reservation=created',flush=True)
    state,_=request('/api/guest/status',cookie=cookie)
    if state.get('status') not in ('PENDING','ACTIVE'):
        raise RuntimeError('Unexpected guest state before activation')
    print('pre_activation_state_valid=true',flush=True)
    for _ in range(30):
        state,_=request('/api/guest/status',cookie=cookie)
        if state.get('status')=='ACTIVE':
            break
        if state.get('status') not in ('PENDING','ACTIVE'):
            raise RuntimeError('Trial unexpectedly declined')
        time.sleep(4)
    if state.get('status')!='ACTIVE':
        raise RuntimeError('Guest VPN not activated by node within 120s')
    print('guest_trial_node_confirmed_active=true',flush=True)
    url=state.get('subscriptionUrl')
    if not isinstance(url,str) or not url.startswith('https://cdn.servgo.ru:8443/sub/'):
        raise RuntimeError('No valid CDN subscription URL')
    token=url.rsplit('/',1)[-1]
    if len(token)!=43:
        raise RuntimeError('Invalid subscription token')
    # Fetch through actual website proxy. Do not print the decoded credential.
    req=urllib.request.Request(BASE+'/sub/'+token,headers={'Cache-Control':'no-cache'})
    with urllib.request.urlopen(req,timeout=12) as res:
        content=res.read(8192)
        if res.status!=200:
            raise RuntimeError('Subscription GET failed')
    decoded=base64.b64decode(content.strip(),validate=True)
    if b'vless://' not in decoded or b'cdn.servgo.ru:8443' not in decoded:
        raise RuntimeError('Live subscription contains no confirmed VLESS config')
    print('guest_trial_real_vless_subscription=verified',flush=True)
    return token,cookie

if __name__=='__main__':
    subscription=None
    error=None
    try:
        subscription,cookie=main()
    except Exception as ex:
        error=ex
        print('guest_trial_live_smoke_failure='+type(ex).__name__,flush=True)
    finally:
        if H and not ID:
            try:ID=entitlement_for_hash(H)
            except Exception:pass
        if ID:
            try:
                revoke(ID)
                if subscription:
                    try:
                        with urllib.request.urlopen(BASE+'/sub/'+subscription,timeout=6):
                            raise RuntimeError('Revoked subscription still accessible')
                    except urllib.error.HTTPError as e:
                        if e.code!=404:raise
                    print('revoked_guest_subscription_http=404',flush=True)
            except Exception as e:
                print('guest_trial_cleanup_failure='+type(e).__name__,flush=True)
                if error is None:error=e
    if error:
        raise SystemExit(2)
    print('website_guest_free_24h_live_flow=verified',flush=True)
